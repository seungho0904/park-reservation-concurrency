CREATE TABLE parks (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    timezone text NOT NULL
);

CREATE TABLE users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    display_name text NOT NULL,
    username text,
    password_hash text,
    CONSTRAINT users_username_unique UNIQUE (username),
    CONSTRAINT users_username_format CHECK (username ~ '^[a-z][a-z0-9_]{2,31}$'),
    CONSTRAINT users_credentials_pair CHECK ((username IS NULL) = (password_hash IS NULL))
);

CREATE TABLE reservation_slots (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    park_id bigint NOT NULL REFERENCES parks (id),
    visit_date date NOT NULL,
    starts_at time NOT NULL,
    ends_at time NOT NULL,
    vehicle_capacity integer NOT NULL CHECK (vehicle_capacity > 0),
    CONSTRAINT slot_time_order CHECK (starts_at < ends_at),
    CONSTRAINT slot_identity UNIQUE (id, park_id, visit_date),
    CONSTRAINT slot_schedule UNIQUE (park_id, visit_date, starts_at, ends_at)
);

CREATE TABLE reservations (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users (id),
    slot_id bigint NOT NULL,
    park_id bigint NOT NULL,
    visit_date date NOT NULL,
    passenger_count integer NOT NULL CHECK (passenger_count BETWEEN 1 AND 8),
    infant_count integer NOT NULL CHECK (infant_count >= 0),
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT reservation_slot_matches FOREIGN KEY (slot_id, park_id, visit_date)
        REFERENCES reservation_slots (id, park_id, visit_date),
    CONSTRAINT one_reservation_per_day UNIQUE (park_id, user_id, visit_date)
);

-- PostgreSQL does not automatically index the referencing side of foreign keys.
-- This index makes counting a slot's reservations efficient.
CREATE INDEX reservations_slot_id_idx ON reservations (slot_id);
CREATE INDEX reservations_user_date_idx ON reservations (user_id, visit_date);

